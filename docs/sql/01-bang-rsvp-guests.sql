create table if not exists public.rsvp_guests (
  id bigint generated by default as identity primary key,
  guest_name text not null,
  phone text not null,
  status text not null default 'yes',
  guest_count integer default 1,
  wishes text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Tự động bù cột nếu bảng đã tạo trước đó bị thiếu
alter table public.rsvp_guests add column if not exists guest_count integer default 1;
alter table public.rsvp_guests add column if not exists wishes text;
alter table public.rsvp_guests add column if not exists status text default 'yes';

-- Kích hoạt Row Level Security (RLS)
alter table public.rsvp_guests enable row level security;

-- Cho phép khách mời gửi xác nhận (Insert công khai)
drop policy if exists "Cho phép khách mời gửi RSVP" on public.rsvp_guests;
create policy "Cho phép khách mời gửi RSVP"
  on public.rsvp_guests for insert
  to public
  with check (true);

-- Cho phép đọc danh sách xác nhận (Select công khai)
drop policy if exists "Cho phép đọc danh sách RSVP" on public.rsvp_guests;
create policy "Cho phép đọc danh sách RSVP"
  on public.rsvp_guests for select
  to public
  using (true);

-- Cho phép tài khoản đã đăng nhập quản trị (Admin) toàn quyền cập nhật và xoá
drop policy if exists "Cho phép thao tác RSVP" on public.rsvp_guests;
create policy "Cho phép thao tác RSVP"
  on public.rsvp_guests for all
  to authenticated
  using (true)
  with check (true);

-- Làm mới schema cache
notify pgrst, 'reload schema';
