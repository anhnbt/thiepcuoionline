-- BƯỚC 6: HẸN GIỜ TỰ ĐỘNG BẰNG pg_cron (NẾU ĐÃ BẬT EXTENSION TRÊN UI)
-- ----------------------------------------------------------------------------
-- LƯU Ý: Hãy bật Extension "pg_cron" trong Supabase: Database → Extensions trước.
-- Đoạn dưới sẽ kiểm tra nếu pg_cron đã được bật thì tự động lên lịch chạy lúc 01:00 UTC (08:00 VN):
do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.schedule(
      'thong-ke-hang-ngay',
      '0 1 * * *',
      'select public.cap_nhat_thong_ke();'
    );
  end if;
exception when others then
  -- Không chặn migration nếu chưa kích hoạt pg_cron
  null;
end $$;

