-- BƯỚC 1: BẢNG KHÁCH MỜI RSVP (rsvp_guests)
-- ----------------------------------------------------------------------------
create table if not exists public.rsvp_guests (
  id bigint generated by default as identity primary key,
  guest_name text not null,
  phone text not null,
  status text not null default 'yes',
  guest_count integer default 1,
  wishes text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Tự động kiểm tra và bù các cột nếu học viên đã tạo bảng cũ từ trước
alter table public.rsvp_guests add column if not exists guest_count integer default 1;
alter table public.rsvp_guests add column if not exists wishes text;
alter table public.rsvp_guests add column if not exists status text default 'yes';

-- Kích hoạt Row Level Security (RLS) cho rsvp_guests
alter table public.rsvp_guests enable row level security;

-- 1.1 Cho phép khách vãng lai gửi phản hồi RSVP (Insert)
drop policy if exists "Cho phép khách mời gửi RSVP" on public.rsvp_guests;
create policy "Cho phép khách mời gửi RSVP"
  on public.rsvp_guests for insert
  to public
  with check (true);

-- 1.2 Cho phép đọc danh sách phản hồi RSVP (Select)
drop policy if exists "Cho phép đọc danh sách RSVP" on public.rsvp_guests;
create policy "Cho phép đọc danh sách RSVP"
  on public.rsvp_guests for select
  to public
  using (true);

-- 1.3 Cho phép tài khoản đã đăng nhập (Admin) toàn quyền cập nhật/xoá (All)
drop policy if exists "Cho phép thao tác RSVP" on public.rsvp_guests;
create policy "Cho phép thao tác RSVP"
  on public.rsvp_guests for all
  to authenticated
  using (true)
  with check (true);


-- BƯỚC 2: BẢNG TỔNG HỢP THEO NGÀY (thong_ke_ngay)
-- ----------------------------------------------------------------------------
create table if not exists public.thong_ke_ngay (
  ngay date primary key,
  so_luong integer not null default 0,
  cap_nhat_luc timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Kích hoạt RLS cho thong_ke_ngay
alter table public.thong_ke_ngay enable row level security;

-- Cho phép đọc thống kê (Select)
drop policy if exists "Cho phép đọc thống kê ngày" on public.thong_ke_ngay;
create policy "Cho phép đọc thống kê ngày"
  on public.thong_ke_ngay for select
  to public
  using (true);


-- BƯỚC 3: HÀM TỔNG HỢP DỮ LIỆU RPC (cap_nhat_thong_ke)
-- ----------------------------------------------------------------------------
create or replace function public.cap_nhat_thong_ke()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.thong_ke_ngay (ngay, so_luong, cap_nhat_luc)
  select
    created_at::date      as ngay,
    count(*)              as so_luong,
    now()                 as cap_nhat_luc
  from public.rsvp_guests
  group by created_at::date
  on conflict (ngay) do update
    set so_luong     = excluded.so_luong,
        cap_nhat_luc = excluded.cap_nhat_luc;
end;
$$;


-- BƯỚC 4: BẢNG QUẢN TRỊ TÀI KHOẢN (admin_users)
-- ----------------------------------------------------------------------------
create table if not exists public.admin_users (
  id uuid default gen_random_uuid() primary key,
  auth_id uuid references auth.users(id) on delete set null,
  email text not null unique,
  full_name text not null,
  phone text,
  side text not null default 'both' check (side in ('groom', 'bride', 'both')),
  role text not null default 'viewer' check (role in ('admin', 'viewer')),
  status text not null default 'active' check (status in ('active', 'inactive')),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table public.admin_users enable row level security;

drop policy if exists "Cho phép tài khoản đăng nhập xem admin_users" on public.admin_users;
create policy "Cho phép tài khoản đăng nhập xem admin_users"
  on public.admin_users for select
  to authenticated
  using (true);

drop policy if exists "Cho phép tài khoản đăng nhập thao tác admin_users" on public.admin_users;
create policy "Cho phép tài khoản đăng nhập thao tác admin_users"
  on public.admin_users for all
  to authenticated
  using (true)
  with check (true);

