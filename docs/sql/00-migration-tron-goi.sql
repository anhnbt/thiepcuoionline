-- BƯỚC 5: TỰ ĐỘNG CHẠY TỔNG HỢP BAN ĐẦU & LÀM MỚI SCHEMA CACHE
-- ----------------------------------------------------------------------------
-- Chạy hàm gom dữ liệu lần đầu
select public.cap_nhat_thong_ke();

-- Ra lệnh PostgREST làm mới bộ nhớ đệm cấu trúc bảng ngay lập tức
